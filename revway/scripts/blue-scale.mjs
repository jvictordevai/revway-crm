#!/usr/bin/env node
// Writes packages/twenty-ui/design-tokens/color/blue.ts with the RevWay blue scale
// (blue9 = #154BD4 light / #5C84FF dark, per revplataform/DESIGN.md), in the same
// shape as upstream: display-p3 solid steps + hex alpha steps.
// After running it, regenerate the theme: `npx nx generateTokens twenty-ui`.
//
// Usage (repo root): node revway/scripts/blue-scale.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const TARGET = path.join(ROOT, 'packages/twenty-ui/design-tokens/color/blue.ts');

// 12-step scale (Radix semantics: 1-2 backgrounds, 3-5 components, 6-8 borders,
// 9-10 solid, 11 low-contrast text, 12 high-contrast text).
const LIGHT = [
  '#FCFDFF', '#F6F8FE', '#ECF1FD', '#E0E8FC', '#D1DDFB', '#BFCEF8',
  '#A6BAF3', '#839EEB', '#154BD4', '#0F41C2', '#1C48C2', '#0B1F5C',
];
const DARK = [
  '#171C2B', '#1A2236', '#1A274B', '#1A2D60', '#203872', '#284485',
  '#31529C', '#3C64BC', '#5C84FF', '#7293FF', '#9DB5FF', '#DCE5FF',
];

// Theme backgrounds the alpha steps composite over (gray1 light / dark).
const LIGHT_BACKGROUND = '#FFFFFF';
const DARK_BACKGROUND = '#171717';

const hexToRgb = (hex) => {
  const value = hex.replace('#', '');

  return [0, 2, 4].map((index) => parseInt(value.slice(index, index + 2), 16));
};

const toLinear = (channel) => {
  const c = channel / 255;

  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};

const fromLinear = (c) =>
  c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;

// sRGB -> XYZ (D65) -> display-p3, both with the sRGB transfer curve.
const SRGB_TO_XYZ = [
  [0.4123908, 0.3575843, 0.1804808],
  [0.212639, 0.7151687, 0.0721923],
  [0.0193308, 0.1191948, 0.9505322],
];
const XYZ_TO_P3 = [
  [2.4934969, -0.9313836, -0.4027108],
  [-0.8294890, 1.7626641, 0.0236247],
  [0.0358458, -0.0761724, 0.9568845],
];

const multiply = (matrix, vector) =>
  matrix.map((row) => row.reduce((sum, value, i) => sum + value * vector[i], 0));

const round3 = (value) =>
  Number(Math.min(1, Math.max(0, value)).toFixed(3)).toString();

const hexToDisplayP3 = (hex) => {
  const linearSrgb = hexToRgb(hex).map(toLinear);
  const p3 = multiply(XYZ_TO_P3, multiply(SRGB_TO_XYZ, linearSrgb)).map(
    fromLinear,
  );

  return `color(display-p3 ${p3.map(round3).join(' ')})`;
};

// Smallest alpha whose overlay on the background reproduces the target color.
const toAlphaHex = (targetHex, backgroundHex) => {
  const target = hexToRgb(targetHex);
  const background = hexToRgb(backgroundHex);

  const alpha = Math.max(
    ...target.map((channel, i) => {
      const bg = background[i];

      if (channel === bg) return 0;

      return channel > bg ? (channel - bg) / (255 - bg) : (bg - channel) / bg;
    }),
  );

  if (alpha === 0) return `${backgroundHex}00`;

  const overlay = target.map((channel, i) =>
    Math.round(
      Math.min(255, Math.max(0, background[i] + (channel - background[i]) / alpha)),
    ),
  );
  const hex = (n) => n.toString(16).padStart(2, '0');
  const alphaByte = Math.round(alpha * 255);

  return `#${overlay.map(hex).join('')}${alphaByte === 255 ? '' : hex(alphaByte)}`;
};

const lines = [
  "import { token } from '../token';",
  '',
  '// RevWay: brand blue scale (blue9 #154BD4 light / #5C84FF dark).',
  '// Generated by revway/scripts/blue-scale.mjs; do not hand-edit.',
  'export const BLUE_COLOR_TOKENS = {',
  '  scale: {',
];

LIGHT.forEach((lightHex, index) => {
  const step = index + 1;

  lines.push(
    `    blue${step}: token({`,
    `      light: '${hexToDisplayP3(lightHex)}',`,
    `      dark: '${hexToDisplayP3(DARK[index])}',`,
    '    }),',
  );
});

lines.push('  },', '  transparent: {');

LIGHT.forEach((lightHex, index) => {
  const step = index + 1;
  const light = toAlphaHex(lightHex, LIGHT_BACKGROUND).toLowerCase();
  const dark = toAlphaHex(DARK[index], DARK_BACKGROUND).toLowerCase();

  lines.push(`    blue${step}: token({ light: '${light}', dark: '${dark}' }),`);
});

lines.push('  },', '};', '');

writeFileSync(TARGET, lines.join('\n'));
console.log(`Wrote ${path.relative(ROOT, TARGET)}`);
